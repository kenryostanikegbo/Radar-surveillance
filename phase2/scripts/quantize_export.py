"""
Quantize Keras model to INT8 TFLite and export as C array header for ESP32-S3.

Steps:
  1. Load Keras model
  2. Convert to TFLite with full INT8 quantization
  3. Verify quantization accuracy didn't drop
  4. Save model_int8.tflite
  5. Convert binary to C array (xxd-style) for embedding in firmware
  6. Generate model_metadata.h with class labels and normalization params

Usage:
    python quantize_export.py \
        --keras models/model.keras \
        --norm models/norm_params.npz \
        --out models/
"""

import argparse
import os
from pathlib import Path

import numpy as np
import tensorflow as tf
from sklearn.metrics import classification_report


CLASS_NAMES = ["human", "vehicle", "unknown"]


def representative_dataset_gen(X_train_n, n_samples=200):
    """Generator that yields samples for TFLite calibration."""
    indices = np.random.choice(len(X_train_n), size=min(n_samples, len(X_train_n)), replace=False)
    for i in indices:
        yield [X_train_n[i:i+1].astype(np.float32)]


def convert_to_int8_tflite(keras_path, X_train_n, out_path):
    """Convert Keras model to full INT8 TFLite."""
    model = tf.keras.models.load_model(keras_path)

    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.target_spec.supported_types = [tf.int8]
    converter.inference_input_type  = tf.int8
    converter.inference_output_type = tf.int8
    converter.representative_dataset = lambda: representative_dataset_gen(X_train_n)

    tflite_model = converter.convert()

    with open(out_path, "wb") as f:
        f.write(tflite_model)

    size_kb = os.path.getsize(out_path) / 1024
    print(f"Saved INT8 TFLite model -> {out_path}  ({size_kb:.1f} KB)")
    return tflite_model


def verify_tflite(tflite_path, X_test_n, y_test):
    """Run inference with the INT8 TFLite model and check accuracy."""
    interpreter = tf.lite.Interpreter(model_path=tflite_path)
    interpreter.allocate_tensors()

    input_details  = interpreter.get_input_details()[0]
    output_details = interpreter.get_output_details()[0]
    input_idx  = input_details["index"]
    output_idx = output_details["index"]
    input_dtype  = input_details["dtype"]
    output_dtype = output_details["dtype"]

    # Quantization parameters for input/output
    input_scale,  input_zero_point  = input_details.get("quantization", (1.0, 0))
    output_scale, output_zero_point = output_details.get("quantization", (1.0, 0))

    correct = 0
    preds = []
    for i in range(len(X_test_n)):
        x = X_test_n[i:i+1]
        if input_dtype == np.int8:
            # Quantize float -> int8 using input scale/zero_point
            x_q = (x / input_scale + input_zero_point).clip(-128, 127).astype(np.int8)
            interpreter.set_tensor(input_idx, x_q)
        else:
            interpreter.set_tensor(input_idx, x.astype(np.float32))

        interpreter.invoke()
        out = interpreter.get_tensor(output_idx)

        if output_dtype == np.int8:
            # Dequantize output back to float for argmax
            out_f = (out.astype(np.float32) - output_zero_point) * output_scale
        else:
            out_f = out

        pred = int(np.argmax(out_f))
        preds.append(pred)
        if pred == y_test[i]:
            correct += 1

    acc = correct / len(y_test)
    print(f"\nTFLite INT8 accuracy: {acc*100:.1f}%")
    print(classification_report(y_test, preds, target_names=CLASS_NAMES, digits=3))


def tflite_to_c_array(tflite_path, c_path, array_name="model_data"):
    """Convert binary TFLite file to C array using xxd-style output."""
    with open(tflite_path, "rb") as f:
        data = f.read()

    # Build header
    lines = []
    lines.append(f"// Auto-generated by quantize_export.py")
    lines.append(f"// Source: {os.path.basename(tflite_path)}")
    lines.append(f"// Size: {len(data)} bytes")
    lines.append(f"#ifndef {array_name.upper()}_H")
    lines.append(f"#define {array_name.upper()}_H")
    lines.append(f"#include <stdint.h>")
    lines.append("")
    lines.append(f"// Alignment helps ESP32-S3 PSRAM fetches")
    lines.append(f"const unsigned int {array_name}_len = {len(data)};")
    lines.append(f"alignas(16) const unsigned char {array_name}[] = {{")

    # 12 bytes per line
    for i in range(0, len(data), 12):
        chunk = data[i:i+12]
        hex_bytes = ", ".join(f"0x{b:02x}" for b in chunk)
        lines.append(f"  {hex_bytes},")

    lines.append("};")
    lines.append("")
    lines.append(f"#endif // {array_name.upper()}_H")

    with open(c_path, "w") as f:
        f.write("\n".join(lines))

    print(f"Saved C array -> {c_path}")


def generate_metadata(out_dir, in_scale=0.079732, in_zp=8, out_scale=0.003906, out_zp=-128):
    """Generate model_metadata.h with class labels, normalization, and
    input/output quantization parameters.

    The defaults match the INT8 model produced by this script (input
    scale ~0.08, output scale ~1/256). When called from main(), the
    actual values are read from the converted tflite model.
    """
    norm = np.load(os.path.join(out_dir, "norm_params.npz"))
    mean = norm["mean"]
    std  = norm["std"]

    lines = []
    lines.append("// Auto-generated by quantize_export.py")
    lines.append("#ifndef MODEL_METADATA_H")
    lines.append("#define MODEL_METADATA_H")
    lines.append("")
    lines.append(f'#define NUM_CLASSES 3')
    lines.append(f'#define FEATURE_DIM  {len(mean)}')
    lines.append("")
    lines.append("// Input/output quantization (int8 TFLite)")
    lines.append(f"#define INPUT_SCALE   {in_scale:.6f}f")
    lines.append(f"#define INPUT_ZP      {in_zp}")
    lines.append(f"#define OUTPUT_SCALE  {out_scale:.6f}f")
    lines.append(f"#define OUTPUT_ZP     {out_zp}")
    lines.append("")
    lines.append("static const char* CLASS_NAMES[NUM_CLASSES] = {")
    for c in CLASS_NAMES:
        lines.append(f'    "{c}",')
    lines.append("};")
    lines.append("")
    lines.append(f"// Feature normalization parameters (z-score)")
    lines.append(f"static const float FEATURE_MEAN[FEATURE_DIM] = {{")
    for i in range(0, len(mean), 8):
        chunk = mean[i:i+8]
        lines.append("    " + ", ".join(f"{v:.6f}f" for v in chunk) + ",")
    lines.append("};")
    lines.append("")
    lines.append(f"static const float FEATURE_STD[FEATURE_DIM] = {{")
    for i in range(0, len(std), 8):
        chunk = std[i:i+8]
        lines.append("    " + ", ".join(f"{v:.6f}f" for v in chunk) + ",")
    lines.append("};")
    lines.append("")
    lines.append("#endif // MODEL_METADATA_H")

    with open(os.path.join(out_dir, "model_metadata.h"), "w") as f:
        f.write("\n".join(lines))

    print(f"Saved metadata -> {out_dir}/model_metadata.h")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--keras", required=True, help="Path to .keras model")
    p.add_argument("--norm",  required=True, help="Path to norm_params.npz")
    p.add_argument("--data",  required=True, help="Path to features npz (for calibration)")
    p.add_argument("--out",   default="models/")
    args = p.parse_args()

    Path(args.out).mkdir(parents=True, exist_ok=True)

    # Load training data for representative dataset
    data = np.load(args.data)
    X = data["X"]
    y_str = data["y"]
    label_to_idx = {c: i for i, c in enumerate(CLASS_NAMES)}
    y = np.array([label_to_idx[label] for label in y_str])

    norm = np.load(args.norm)
    mean, std = norm["mean"], norm["std"]
    X_n = (X - mean) / std

    # Split for verification
    from sklearn.model_selection import train_test_split
    _, X_test_n, _, y_test = train_test_split(X_n, y, test_size=0.2,
                                              stratify=y, random_state=42)

    # Convert
    tflite_path = os.path.join(args.out, "model_int8.tflite")
    convert_to_int8_tflite(args.keras, X_n, tflite_path)

    # Verify
    print("\nVerifying INT8 TFLite accuracy...")
    verify_tflite(tflite_path, X_test_n, y_test)

    # Export C array
    c_path = os.path.join(args.out, "model_data.cc")
    tflite_to_c_array(tflite_path, c_path)

    # Read input/output quantization from the generated model and
    # write them into the metadata header.
    import tensorflow as tf
    interp = tf.lite.Interpreter(model_path=tflite_path)
    interp.allocate_tensors()
    in_det  = interp.get_input_details()[0]
    out_det = interp.get_output_details()[0]
    in_scale,  in_zp  = in_det.get("quantization",  (1.0, 0))
    out_scale, out_zp = out_det.get("quantization", (1.0, 0))
    if in_scale == 1.0 and in_zp == 0:
        # Model is float; fall back to defaults the firmware uses.
        in_scale, in_zp = 1.0 / 127.0, 0

    generate_metadata(args.out, in_scale=in_scale, in_zp=int(in_zp),
                      out_scale=out_scale, out_zp=int(out_zp))


if __name__ == "__main__":
    main()
